def _buscar(bind, tabla, nombre):
    fila = bind.execute(
        sa.text(f"SELECT id FROM {tabla} WHERE upper(trim(nombre)) = upper(:nombre)"),
        {"nombre": nombre},
    ).first()
    return _uuid(fila[0]) if fila else None


def _crear(bind, tabla_obj, nombre, extra):
    nuevo = uuid.uuid4()
    op.bulk_insert(tabla_obj, [{"id": nuevo, "nombre": nombre, **extra}])
    return nuevo


def _upsert_tarifa(bind, comisionista_id, cliente_id, producto_id, finca_id, tipo, valor, vigente):
    fila = bind.execute(
        sa.text(
            "SELECT id FROM tarifas_cliente_producto "
            "WHERE comisionista_id = :c AND cliente_id = :cl AND producto_id = :p "
            "AND finca_id IS NOT DISTINCT FROM :f AND proveedor = '' "
            "AND vigente_desde IS NOT DISTINCT FROM :v"
        ),
        {"c": comisionista_id, "cl": cliente_id, "p": producto_id, "f": finca_id, "v": vigente},
    ).first()
    if fila:
        bind.execute(
            sa.text(
                "UPDATE tarifas_cliente_producto "
                "SET tipo = CAST(:tipo AS tipo_tarifa), valor = :valor, activo = true "
                "WHERE id = :id"
            ),
            {"id": _uuid(fila[0]), "tipo": tipo, "valor": Decimal(valor)},
        )
        return
    op.bulk_insert(
        _tabla_tarifas(),
        [{"id": uuid.uuid4(), "comisionista_id": comisionista_id, "cliente_id": cliente_id,
          "producto_id": producto_id, "finca_id": finca_id, "proveedor": "",
          "proveedores_excluidos": [], "tipo": tipo, "valor": Decimal(valor),
          "activo": True, "vigente_desde": vigente}],
    )


